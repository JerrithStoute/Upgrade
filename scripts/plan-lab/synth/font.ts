const NARROW: Record<string, number> = { "'": 2, '"': 2.6, ".": 1.5, ",": 1.5, ":": 1.5, "(": 2.6, ")": 2.6, " ": 3, I: 4 };
const adv = (ch: string) => (NARROW[ch] ?? 4) + 1.2;

/** Width of `text` at a cap height `h`. */
export const strokeWidth = (text: string, h: number) => ([...text].reduce((s, ch) => s + adv(ch), 0) - 1.2) * (h / 6);

/**
 * `text` as polylines with cap height `h`, centered on `at`, its baseline along `angle` (radians, y down: 0 = left
 * to right, -π/2 = reads bottom to top). `slant` leans it like hand lettering.
 */
export function strokeText(text: string, at: [number, number], h: number, angle = 0, slant = 0): [number, number][][] {
  const k = h / 6, W = strokeWidth(text, h);
  const c = Math.cos(angle), s = Math.sin(angle);
  const out: [number, number][][] = [];
  let x = -W / 2;
  for (const ch of text.toUpperCase()) {
    for (const line of GLYPHS[ch] ?? [])
      out.push(
        line.map(([gx, gy]) => {
          const lx = x + (gx + gy * slant) * k, ly = -(gy - 3) * k; // y down, centered on the cap height
          return [at[0] + lx * c - ly * s, at[1] + lx * s + ly * c];
        }),
      );
    x += adv(ch) * k;
  }
  return out;
}
